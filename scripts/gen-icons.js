#!/usr/bin/env node
/**
 * 把 src/assets/*.svg 生成成 C 头文件 src/generated/icon_svgs.h，
 * 以及（macOS 有 clang 时）Swift 图标文件 src/generated/icon_svgs.swift。
 *
 * C 输出形如：
 *   static const char* kIconSvg_Rect = "<svg ...>...</svg>";
 * SVG 原文原样保留（含 currentColor），运行时再把 currentColor 替换成
 * 目标颜色（normal/hover/active 三态），从而一套文本支持多色。
 *
 * Swift 输出：生成期用 clang 现编一个极小 nanosvg 光栅化辅助程序
 * （单实例化编译单元，参照 icons_windows.cpp 的宏实例化写法），把每个 SVG
 * （currentColor→黑色）光栅化为 PNG（2x、内容 72% 居中）→ base64 内联进
 * icon_svgs.swift；运行时 NSImage(data:) 解码为 template 图标并按需着色出
 * normal/hover/active 三态缓存，等价 Windows icons_windows.cpp 的双色位图缓存。
 * clang 不可用（如 Windows）时跳过 Swift 输出（文件已提交进仓库，不受影响）。
 *
 * 自动生成，请勿手动编辑。重新生成命令：node scripts/gen-icons.js
 */
